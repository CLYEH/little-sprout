// 手寫字標「小芽」——全稿唯一的非系統線條。
//
// 為什麼是手寫：歡迎頁的溫度不能靠「暖色底＋系統粗體」硬撐，那是每個 app 都有的東西。
// 一支有起筆、有提按、有收鋒的筆跡，是這個 app 唯一做得出來、別人抄不走的東西 ——
// 而且它可以跨板再現（信件明細的「寄件人 小芽」、建立家庭的即時預覽），把流程縫起來。
//
// 做法：每一筆給一條三次貝茲中線 + 起筆寬 + 收筆寬 + 中段提按，
// 取樣後往法線兩側推出外框，輸出成填色多邊形。所以筆畫真的有粗細變化，
// 不是「圓頭 stroke 假裝手寫」。

const bez = (p, u) => {
  const v = 1 - u, a = v * v * v, b = 3 * v * v * u, c = 3 * v * u * u, d = u * u * u;
  return [a * p[0][0] + b * p[1][0] + c * p[2][0] + d * p[3][0],
    a * p[0][1] + b * p[1][1] + c * p[2][1] + d * p[3][1]];
};

const r2 = (n) => Math.round(n * 100) / 100;

// pts: 四個控制點 [起, c1, c2, 終]；w0/w1 起訖筆寬；swell 中段提按（0 = 沒有）
const stroke = (pts, w0, w1, swell = 0) => {
  const N = 26, L = [], R = [];
  for (let i = 0; i <= N; i++) {
    const u = i / N;
    const [x, y] = bez(pts, u);
    const [x2, y2] = bez(pts, Math.min(1, u + 0.004));
    const [x1, y1] = bez(pts, Math.max(0, u - 0.004));
    let tx = x2 - x1, ty = y2 - y1;
    const len = Math.hypot(tx, ty) || 1;
    tx /= len; ty /= len;
    const w = (w0 + (w1 - w0) * u) * (1 + swell * Math.sin(Math.PI * u)) / 2;
    L.push([r2(x - ty * w), r2(y + tx * w)]);
    R.push([r2(x + ty * w), r2(y - tx * w)]);
  }
  const path = [`M${L[0][0]} ${L[0][1]}`];
  for (let i = 1; i <= N; i++) path.push(`L${L[i][0]} ${L[i][1]}`);
  for (let i = N; i >= 0; i--) path.push(`L${R[i][0]} ${R[i][1]}`);
  return `<path d="${path.join('')}Z"/>`;
};

/* ── 小（0–100 見方）───────────────────────────────
   三筆：豎鉤（起筆重、收鋒往左上挑出）、左點（下按）、右點（下按）。
   兩點要收得住 —— 撇太開就變成「八」。 */
const XIAO = [
  stroke([[50, 15], [53, 33], [51.5, 53], [50, 70]], 10.4, 7),               // 豎
  stroke([[50, 70], [49, 79], [43, 85], [31, 82]], 7, 1),                    // 鉤
  stroke([[34, 29], [31, 38], [28, 48], [25, 61]], 2.6, 9.6, .1),            // 左點
  stroke([[67, 27], [70, 36], [73, 46], [76, 59]], 2.4, 9.2, .1),            // 右點
].join('');

/* ── 芽（0–100 見方）─────────────────────────────────
   艹：長橫 + 左短豎 + 右短豎（兩豎只稍微出頭，出頭太長會變成「廾」）。
   牙：左上短撇、長橫、長撇（穿過長橫落到左下）、右豎鉤。 */
const YA = [
  // 艹
  stroke([[7, 24.5], [32, 21.8], [62, 20.2], [92, 18]], 5, 8, .07),          // 長橫
  stroke([[31, 11], [30, 18], [29, 26], [27.5, 35]], 6.2, 4.6),                // 左短豎
  stroke([[67.5, 10], [69, 18], [70.5, 26], [72, 35]], 4.8, 6.6),                // 右短豎
  // 牙
  stroke([[64, 37.5], [55, 42], [43, 47], [27, 52.5]], 6.6, 1.8, .06),       // 左上短撇
  stroke([[10, 60.5], [34, 58.4], [62, 56.8], [90, 55]], 5, 8, .06),         // 長橫
  stroke([[60, 40], [51, 59], [35, 78], [11, 96]], 8, 1.4, .07),             // 長撇
  stroke([[72.8, 32.5], [72, 52], [71.4, 70], [70.6, 86]], 8.6, 6.4),            // 右豎
  stroke([[70.6, 86], [69, 92.5], [63, 96.5], [51, 94]], 6.4, 1),            // 鉤
].join('');

/* 兩字並排：手寫的字不會排得像表格 —— 第二個字微微下沉、微微轉一點，
   是筆跡自然的參差。 */
// viewBox 貼著墨跡的外框（不是 0–202 見方）—— 這樣字標的左緣可以跟標題切齊，
// 不會因為第一筆是細鋒而看起來內縮。
export const inkMark = (size, color, title = '小芽') => {
  const h = Math.round(size), w = Math.round(size * 182 / 94);
  return `<svg width="${w}" height="${h}" viewBox="13 4 182 94" fill="${color}" role="img" aria-label="${title}">
    <g transform="translate(2 2) rotate(-1.4 50 50) scale(.95)">${XIAO}</g>
    <g transform="translate(100 -1) rotate(.9 50 50)">${YA}</g>
  </svg>`;
};
